/** Candidate-only guidance and the canonical effect/recovery model. */
import { defineErrors, recoveryFacts, kernelErrors, protocolLimits, type AnyCommitReport, type AnyResult, type CompactRecovery, type OperationOutcome, type ResponseError, type CliError, type SecondaryFailure } from "cli-for-agents";
import { evaluateGuidance, defineSteering, instruction, type EvaluatedGuidance, type GuidanceCandidate } from "cli-for-agents/guidance";
import { family, readSpec, read } from "./runner-positive.js";
import { arbitrate, type ArbitrationInput } from "../src/internal/response.js";
import { invocation } from "cli-for-agents";
declare function accepts<T>(value: T): void;
const command = family.defineCommand(readSpec, { examples: [{ why: "Read" }], handler: async () => ({ default: read }) });
const continuation = invocation(command, {});
const errors = defineErrors({ DENIED: { exitClass: "failed", description: "Denied" }, OFFLINE: { exitClass: "connection", description: "Offline" } });
const denied = errors.error("DENIED", { message: "Denied", why: "Contextual rationale" });
const offline = errors.error("OFFLINE", { message: "Offline", continuation });
accepts<CliError<"OFFLINE", "connection">>(offline);
const recovery = recoveryFacts([{ kind: "receipt", id: "app-reported-id" }]);
accepts<CompactRecovery>(recovery);
accepts<AnyCommitReport>({ effect: "applied", recovery, result: { ok: true, data: null } });
accepts<AnyCommitReport>({ effect: "applied", recovery, result: { ok: false, error: denied } });
accepts<AnyCommitReport>({ effect: "unknown", recovery, result: { ok: false, error: offline } });
accepts<AnyCommitReport>({ effect: "not_applied", result: { ok: false, error: denied } });
accepts<OperationOutcome>({ operation: { effect: "applied", recovery }, result: { ok: false, error: denied } });
accepts<ResponseError<"OFFLINE", "connection">>({ ...offline, why: "Offline", doctor: continuation, secondary: [{ code: "KERNEL_OUTPUT", message: "Artifact failed" }] });
accepts<SecondaryFailure>({ code: "KERNEL_RELEASE", message: "Release failed" });
accepts<"connection">(kernelErrors.KERNEL_CONTEXT.exitClass);
accepts<8192>(protocolLimits.minimumOutput);
const rule = defineSteering<{}>({ id: "stop", appliesTo: [command], when: () => true, tier: "instruction", render: () => instruction("policy", "Wait for review.") });
const evaluation = evaluateGuidance({ command, state: {}, rules: [rule], eventSink: event => { accepts<"guidance.rule_fired">(event.type); } });
accepts<Promise<EvaluatedGuidance>>(evaluation);
declare const batch: EvaluatedGuidance;
accepts<readonly GuidanceCandidate[]>(batch.candidates);
const input: ArbitrationInput = { commandPath: "read", handler: { instruction: instruction("handler", "Wait.") }, evaluated: batch, conflictSink: event => { accepts<"guidance.conflict">(event.type); } };
arbitrate(input);
accepts<AnyResult>({ ok: true, data: null, issues: batch.issues });

// An automatic spill discloses the attempted inline size beside the artifact manifest.
import { bytes, type AnyPayload, type ArtifactManifest } from "cli-for-agents";
declare const manifest: ArtifactManifest;
accepts<AnyPayload>({ kind: "artifact", artifact: manifest, summary: { omitted: true }, spill: { format: "text", inlineBytes: bytes(40000), maxBytes: bytes(32768) } });
accepts<AnyPayload>({ kind: "artifact", artifact: manifest, summary: null });
declare const spilled: Extract<AnyPayload, { kind: "artifact" }>;
if (spilled.spill) accepts<"text" | "json">(spilled.spill.format);
