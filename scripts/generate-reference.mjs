#!/usr/bin/env node
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { commandReference, writeCommandReference } from 'cli-for-agents/runtime';
import { bytes } from 'cli-for-agents';

try {
  const { values } = parseArgs({ strict: true, allowPositionals: false, options: {
    check: { type: 'boolean', default: false },
    file: { type: 'string', default: fileURLToPath(new URL('../docs/reference-fixture/reference.md', import.meta.url)) },
    fixture: { type: 'string', default: fileURLToPath(new URL('./fixtures/reference-cli.mjs', import.meta.url)) },
    marker: { type: 'string', default: 'COMMAND REFERENCE' },
    'max-bytes': { type: 'string', default: '1048576' },
  } });
  if (!/^(0|[1-9][0-9]*)$/.test(values['max-bytes'])) throw new TypeError('Expected an integer --max-bytes.');
  const cli = (await import(pathToFileURL(resolve(values.fixture)).href)).default;
  const generated = commandReference(cli);
  const result = await writeCommandReference(cli, { path: values.file, marker: values.marker, mode: values.check ? 'check' : 'write', maxBytes: bytes(Number(values['max-bytes'])), signal: new AbortController().signal });
  if (!result.ok) {
    process.stderr.write(result.issues.map(issue => `${issue.code}: ${issue.commandPath}: ${issue.reference}`).join('\n') + '\n');
    process.exitCode = 1;
  } else if (values.check && result.changed) {
    process.stderr.write(`Reference drift: ${values.file}; regenerate without --check.\n`);
    process.exitCode = 1;
  } else {
    process.stdout.write(`${values.check ? 'Checked' : result.changed ? 'Updated' : 'Unchanged'} ${values.file} (${new TextEncoder().encode(generated).length} generated bytes).\n`);
  }
} catch (error) {
  process.stderr.write(`Reference generation failed: ${error instanceof Error ? error.message : 'invalid request'}\n`);
  process.exitCode = 2;
}
